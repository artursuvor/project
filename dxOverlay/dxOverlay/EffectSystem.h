#pragma once

#include <Windows.h>
#include "Types.h"

/**
 * @file EffectSystem.h
 * @brief Управление системой эффектов и состоянием приложения
 * 
 * Сердце приложения - отвечает за:
 * - Инициализацию и управление эффектами
 * - Переходы между состояниями (Off -> Waiting -> Rolling -> Effect)
 * - Тайминги и длительность эффектов
 * - API для DEV/DEBUG панели управления
 */

// ============================================================================
// INITIALIZATION
// ============================================================================

/**
 * @brief Инициализация системы эффектов
 * @param overlayHwnd Handle окна оверлея для рисования эффектов
 * 
 * Должна быть вызвана один раз при запуске приложения
 */
void InitEffectSystem(HWND overlayHwnd);

// ============================================================================
// SYSTEM CONTROL
// ============================================================================

/**
 * @brief Запустить систему (начать ожидание до автоматического вращения рулетки)
 */
void StartSystem();

/**
 * @brief Полностью остановить систему и все активные эффекты
 */
void StopSystem();

/**
 * @brief Обновить состояние системы (должна вызываться из message loop)
 * 
 * Эта функция проверяет тайминги и переводит систему между состояниями
 */
void UpdateEffectSystem();

// ============================================================================
// STATE QUERIES
// ============================================================================

/**
 * @brief Получить текущее состояние системы
 * @return Текущее состояние (Off, Waiting, Rolling, Effect)
 */
SystemState GetSystemState();

/**
 * @brief Получить тип активного эффекта
 * @return EffectType::None если эффекта нет
 */
EffectType GetCurrentEffect();

/**
 * @brief Проверить, активен ли эффект в данный момент
 * @return true если эффект еще действует
 */
bool IsEffectAlive();

/**
 * @brief Получить оставшееся время эффекта в миллисекундах
 * @return Оставшееся время или 0 если эффекта нет
 */
DWORD GetEffectRemainingTime();

// ============================================================================
// ROULETTE CONTROL
// ============================================================================

/**
 * @brief Получить текущее состояние визуализации рулетки
 * @return Состояние рулетки
 */
RouletteVisualState GetRouletteVisualState();

/**
 * @brief Получить текущую позицию вращения рулетки
 * @return Индекс выбранного элемента
 */
int GetRouletteCurrentIndex();

/**
 * @brief Получить финальный выбранный индекс рулетки
 * @return Индекс эффекта, который будет активирован
 */
int GetRouletteFinalIndex();

/**
 * @brief Получить коэффициент затухания рулетки (для FadeOut)
 * @return Значение альфа-канала от 0 до 255
 */
BYTE GetRouletteFadeAlpha();

// ============================================================================
// DEV / DEBUG API
// ============================================================================

/**
 * @brief DEV: Остановить текущий эффект
 * 
 * Используется для тестирования - позволяет сразу остановить эффект
 */
void Dev_StopEffect();

/**
 * @brief DEV: Запустить конкретный эффект по типу
 * @param type Какой эффект запустить
 * 
 * Минует рулетку и сразу запускает нужный эффект
 */
void Dev_ForceEffect(EffectType type);

/**
 * @brief DEV: Принудительно запустить рулетку
 * 
 * Пропускает ожидание Waiting и сразу вращает рулетку
 */
void Dev_ForceRoulette();

/**
 * @brief DEV: Запустить превью рулетки (без активации эффекта)
 * 
 * Показывает визуализацию рулетки, но эффект не активируется
 */
void Dev_StartPreviewRoulette();

/**
 * @brief DEV: Остановить превью рулетки
 */
void Dev_StopPreviewRoulette();

/**
 * @brief DEV: Проверить, находимся ли в режиме превью рулетки
 * @return true если рулетка в режиме превью
 */
bool IsPreviewRoulette();
