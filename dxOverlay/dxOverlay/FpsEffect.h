#pragma once

/**
 * @file FpsEffect.h
 * @brief Эффект понижения FPS в игре
 *
 * Понижает максимальный FPS установкой fps_max = 16 в консоли игры
 */

/**
 * @brief Запустить эффект (понизить FPS)
 *
 * Эффект:
 * - Открывает консоль игры
 * - Выполняет команду: fps_max 16
 * - Закрывает консоль
 */
void StartFpsLowEffect();

/**
 * @brief Остановить эффект (восстановить нормальный FPS)
 *
 * Эффект:
 * - Открывает консоль игры
 * - Выполняет команду: fps_max 128 (оригинальное значение)
 * - Закрывает консоль
 */
void StopFpsLowEffect();
