#pragma once

#include <Windows.h>

/**
 * @file BlurEffect.h
 * @brief Эффект размытия экрана
 *
 * Отрисовывает горизонтальные линии поверх экрана,
 * создавая эффект размытия. Линии появляются в случайных местах
 */

/**
 * @brief Запустить эффект размытия
 * @param hwnd Handle окна оверлея
 *
 * Инициализирует таймер для обновления линий размытия
 */
void StartBlurEffect(HWND hwnd);

/**
 * @brief Остановить эффект размытия
 * @param hwnd Handle окна оверлея
 *
 * Останавливает таймер и очищает линии
 */
void StopBlurEffect(HWND hwnd);

/**
 * @brief Получить количество линий размытия для отрисовки
 * @return Количество горизонтальных линий на экране
 *
 * Используется в WM_PAINT для отрисовки всех линий
 */
int GetBlurLineCount();

/**
 * @brief Обновить линии размытия (вызывается из таймера)
 *
 * Генерирует новые случайные линии в случайных местах
 */
void UpdateBlurEffect();
