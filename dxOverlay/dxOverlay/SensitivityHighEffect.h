#pragma once

/**
 * @file SensitivityHighEffect.h
 * @brief Эффект максимальной чувствительности мыши
 *
 * Максимально увеличивает контроль мыши установкой sensitivity = 7.0 в консоли игры
 */

/**
 * @brief Запустить эффект (включить максимальную чувствительность)
 *
 * Эффект:
 * - Открывает консоль игры
 * - Выполняет команду: sensitivity 7.0
 * - Закрывает консоль
 */
void StartSensitivityHighEffect();

/**
 * @brief Остановить эффект (восстановить нормальную чувствительность)
 *
 * Эффект:
 * - Открывает консоль игры
 * - Выполняет команду: sensitivity 0.2 (оригинальное значение)
 * - Закрывает консоль
 */
void StopSensitivityHighEffect();
