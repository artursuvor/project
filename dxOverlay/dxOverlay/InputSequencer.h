#pragma once

#include <Windows.h>

/**
 * @file InputSequencer.h
 * @brief Низкоуровневая работа с вводом и буфером обмена
 *
 * Предоставляет функции для:
 * - Отправки виртуальных нажатий клавиш
 * - Работы с буфером обмена
 */

// ============================================================================
// LOW-LEVEL KEY INPUT
// ============================================================================

/**
 * @brief Отправить виртуальное нажатие клавиши
 * @param vk Виртуальный код клавиши (VK_*)
 * @param down true для нажатия, false для отпускания
 */
void SendKey(WORD vk, bool down);

/**
 * @brief Отправить короткое нажатие клавиши (down + up)
 * @param vk Виртуальный код клавиши (VK_*)
 */
void SendKeyPress(WORD vk);

// ============================================================================
// COMMON KEY COMBINATIONS
// ============================================================================

/**
 * @brief Выполнить Ctrl+V (вставить из буфера обмена)
 */
void PressCtrlV();

/**
 * @brief Выполнить Enter (подтвердить команду)
 */
void PressEnter();

/**
 * @brief Выполнить F7 (открыть/закрыть консоль)
 */
void PressF7();

// ============================================================================
// CLIPBOARD OPERATIONS
// ============================================================================

/**
 * @brief Установить текст в буфер обмена
 * @param text Строка, которую нужно скопировать (null-terminated wide string)
 *
 * Используется для передачи команд консоли игры через буфер обмена
 */
void SetClipboardText(const wchar_t* text);
