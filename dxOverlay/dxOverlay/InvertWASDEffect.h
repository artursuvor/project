#pragma once

/**
 * @file InvertWASDEffect.h
 * @brief Эффект инверсии клавиш управления (WASD)
 *
 * Переворачивает клавиши движения:
 * - W (вперед) → S (назад)
 * - A (влево) → D (вправо)
 * - S (назад) → W (вперед)
 * - D (вправо) → A (влево)
 */

/**
 * @brief Запустить эффект инверсии WASD
 *
 * Активирует низкоуровневый хук для перехвата клавиш
 */
void StartInvertWASD();

/**
 * @brief Остановить эффект инверсии WASD
 *
 * Деактивирует хук и восстанавливает нормальные клавиши
 */
void StopInvertWASD();
