#pragma once

/**
 * @file InvertMouseEffect.h
 * @brief Эффект инверсии управления мышью
 * 
 * Переворачивает управление мышью по осям X и Y,
 * чтобы игрок не мог нормально смотреть/целиться
 */

/**
 * @brief Запустить эффект инверсии мыши
 * 
 * Активирует низкоуровневый хук, который инвертирует все движения мыши
 */
void StartInvertMouseEffect();

/**
 * @brief Остановить эффект инверсии мыши
 * 
 * Деактивирует хук и восстанавливает нормальное управление
 */
void StopInvertMouseEffect();
